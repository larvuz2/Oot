#!/usr/bin/env python3
"""Generate web/js/versions.js from baseroms/*/ (checksums + config.yml).

The web player uses this table to recognise a player's ROM dump, decompress it
exactly like tools/decompress_baserom.py, and pick the matching remix patch.
Re-run after pulling upstream changes that add or alter ROM versions:

    python3 tools/web/gen_versions.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

LABELS = {
    "ntsc-1.0": "N64 NTSC 1.0",
    "ntsc-1.1": "N64 NTSC 1.1",
    "ntsc-1.2": "N64 NTSC 1.2",
    "pal-1.0": "N64 PAL 1.0",
    "pal-1.1": "N64 PAL 1.1",
    "gc-jp": "GameCube Japan",
    "gc-jp-mq": "GameCube Japan Master Quest",
    "gc-jp-ce": "GameCube Japan (Collector's Edition)",
    "gc-us": "GameCube US",
    "gc-us-mq": "GameCube US Master Quest",
    "gc-eu": "GameCube Europe",
    "gc-eu-mq": "GameCube Europe Master Quest",
    "gc-eu-dbg": "GameCube Europe Debug",
    "gc-eu-dbg-2": "GameCube Europe Debug (earlier build)",
    "gc-eu-mq-dbg": "GameCube Europe Master Quest Debug",
    "ique-cn": "iQue Player (Simplified Chinese)",
}

# Mirrors per_version_fixes() in tools/decompress_baserom.py.
FIXES = {
    "gc-eu-mq-dbg": {"truncate": 0x035CF000, "patch": [[0x3E, 0x50]]},
    "gc-eu-dbg": {"truncate": 0x035C3000, "patch": []},
    "gc-eu-dbg-2": {"truncate": 0x035C3000, "patch": []},
}


def default_region(version: str) -> str:
    if version.startswith("ique"):
        return "CN"
    if version.startswith("pal") or version.startswith("gc-eu"):
        return "EU"
    if version.startswith("gc-us"):
        return "US"
    return "JP"


def collect() -> list[dict]:
    """One entry per (version, region) the decomp can build, keyed by ROM checksums."""
    entries = []
    for cfg_path in sorted((ROOT / "baseroms").glob("*/config.yml")):
        vdir = cfg_path.parent
        version = vdir.name
        cfg = cfg_path.read_text()
        dmadata_start = int(re.search(r"^dmadata_start:\s*(0x[0-9A-Fa-f]+)", cfg, re.M).group(1), 16)
        stems = re.search(r"^checksums:\n((?:\s+- .+\n)+)", cfg, re.M)
        for stem in re.findall(r"- (\S+)", stems.group(1)) if stems else ["checksum"]:
            m = re.fullmatch(r"checksum(?:-(\w+))?", stem)
            region = m.group(1) or default_region(version)
            md5 = lambda name: (vdir / name).read_text().split()[0]
            entries.append(
                {
                    "version": version,
                    "region": region,
                    "label": f"{LABELS.get(version, version)}"
                    + (f" ({region})" if m.group(1) else ""),
                    "compressedMd5": md5(f"{stem}-compressed.md5"),
                    "decompressedMd5": md5(f"{stem}.md5"),
                    "dmadataStart": dmadata_start,
                    "ique": version.startswith("ique-"),
                    "fix": FIXES.get(version),
                }
            )
    return entries


def main() -> None:
    entries = collect()
    out = ROOT / "web" / "js" / "versions.js"
    out.write_text(
        "// Generated by tools/web/gen_versions.py from baseroms/*/ - do not edit by hand.\n"
        "export const VERSIONS = "
        + json.dumps(entries, indent=4)
        + ";\n"
    )
    print(f"Wrote {len(entries)} entries to {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
