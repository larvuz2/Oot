static void RemixMenu_RefreshButtons(PlayState* play) {
    s32 i;

    // C buttons show whatever item now sits in their inventory slot.
    for (i = 1; i < 4; i++) {
        u8 slot = gSaveContext.save.info.equips.cButtonSlots[i - 1];

        if (slot != SLOT_NONE) {
            gSaveContext.save.info.equips.buttonItems[i] = gSaveContext.save.info.inventory.items[slot];
        }
    }
    for (i = 0; i < 4; i++) {
        if (gSaveContext.save.info.equips.buttonItems[i] < ITEM_NONE_FE) {
            Interface_LoadItemIcon1(play, i);
        }
    }
    Player_SetEquipmentData(play, GET_PLAYER(play));
}

