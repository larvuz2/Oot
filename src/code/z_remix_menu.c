void RemixMenu_Draw(PlayState* play) {
    GraphicsContext* gfxCtx = play->state.gfxCtx;
    GfxPrint printer;
    Gfx* gfx;
    Gfx* gfxRef;

    if (!sRemix.isOpen && (sRemix.messageTimer == 0)) {
        return;
    }

    OPEN_DISPS(gfxCtx, "../z_remix_menu.c", __LINE__);

    if (sRemix.isOpen) {
        // Dim panel behind the text.
        Gfx_SetupDL_39Overlay(gfxCtx);
        gDPSetCycleType(OVERLAY_DISP++, G_CYC_1CYCLE);
        gDPSetRenderMode(OVERLAY_DISP++, G_RM_XLU_SURF, G_RM_XLU_SURF2);
        gDPSetCombineMode(OVERLAY_DISP++, G_CC_PRIMITIVE, G_CC_PRIMITIVE);
        gDPSetPrimColor(OVERLAY_DISP++, 0, 0, 0, 10, 20, 190);
        gDPFillRectangle(OVERLAY_DISP++, (REMIX_COL - 1) * 8, (REMIX_ROW - 1) * 8, 37 * 8, (REMIX_ROW + 17) * 8);
        gDPPipeSync(OVERLAY_DISP++);
    }

    // Text goes into the POLY_OPA buffer as a sub-list called from the overlay list,
    // the same way the developers' debug printers do it (see z_kankyo.c).
    gfxRef = POLY_OPA_DISP;
    gfx = Gfx_Open(gfxRef);
    gSPDisplayList(OVERLAY_DISP++, gfx);

    GfxPrint_Init(&printer);
    GfxPrint_Open(&printer, gfx);

    if (sRemix.isOpen) {
        if (sRemix.page == REMIX_PAGE_MAIN) {
            RemixMenu_PrintMain(&printer);
        } else {
            RemixMenu_PrintSpawn(&printer);
        }
        GfxPrint_SetPos(&printer, REMIX_COL, REMIX_ROW + 15);
        GfxPrint_SetColor(&printer, 150, 150, 150, 255);
        GfxPrint_Printf(&printer, "D-Pad/Stick:Move A:OK B:Back");
    }
    if ((sRemix.messageTimer > 0) && (sRemix.message != NULL)) {
        GfxPrint_SetPos(&printer, REMIX_COL, sRemix.isOpen ? REMIX_ROW + 16 : 26);
        GfxPrint_SetColor(&printer, 255, 255, 120, 255);
        GfxPrint_Printf(&printer, "%s", sRemix.message);
    }

    gfx = GfxPrint_Close(&printer);
    GfxPrint_Destroy(&printer);
    gSPEndDisplayList(gfx++);
    Gfx_Close(gfxRef, gfx);
    POLY_OPA_DISP = gfx;

    CLOSE_DISPS(gfxCtx, "../z_remix_menu.c", __LINE__);
}
