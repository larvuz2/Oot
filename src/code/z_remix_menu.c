static s32 RemixMenu_NumListed(void) {
    s32 i;
    s32 n = 0;

    if (sRemix.listAll) {
        return ARRAY_COUNT(sRemixActors);
    }
    for (i = 0; i < ARRAY_COUNT(sRemixActors); i++) {
        if (sRemixActors[i].favorite) {
            n++;
        }
    }
    return n;
}

static s32 RemixMenu_CanOpen(PlayState* play) {
    return (gSaveContext.gameMode == GAMEMODE_NORMAL) && !IS_PAUSED(&play->pauseCtx) &&
           (play->msgCtx.msgMode == MSGMODE_NONE) && (play->transitionTrigger == TRANS_TRIGGER_OFF) &&
           (play->transitionMode == TRANS_MODE_OFF) && (play->gameOverCtx.state == GAMEOVER_INACTIVE) &&
           (play->csCtx.state == CS_STATE_IDLE) && (GET_PLAYER(play) != NULL);
}

static void RemixMenu_Open(void) {
    sRemix.isOpen = true;
    sRemix.page = REMIX_PAGE_MAIN;
    sRemix.cursor = 0;
    // IREG(72) is the developers' "freeze gameplay" switch: actors, collision and rooms stop updating.
    sRemix.savedFreezeReg = IREG(72);
    IREG(72) = 1;
    SFX_PLAY_CENTERED(NA_SE_SY_DECIDE);
}

static void RemixMenu_Close(void) {
    sRemix.isOpen = false;
    IREG(72) = sRemix.savedFreezeReg;
    SFX_PLAY_CENTERED(NA_SE_SY_CANCEL);
}

