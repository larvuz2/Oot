/**
 * Called by Play_SpawnScene. While a biome is on, Hyrule Field loads the restyled copy of its scene file
 * instead of the original. Everything else (scene id, exits, music, minimap, actors) stays Hyrule Field's,
 * since the copy has the same rooms, collision and spawns: only textures, vertex colors and lighting differ.
 */
SceneTableEntry* RemixBiome_OverrideScene(PlayState* play, s32 sceneId, SceneTableEntry* scene) {
#if REMIX_HAS_TUNDRA
    static SceneTableEntry sTundraScene;

    (void)play;
    if ((sRemix.biome == REMIX_BIOME_TUNDRA) && (sceneId == SCENE_HYRULE_FIELD)) {
        sTundraScene = *scene;
        sTundraScene.sceneFile.vromStart = (uintptr_t)_tundra_sceneSegmentRomStart;
        sTundraScene.sceneFile.vromEnd = (uintptr_t)_tundra_sceneSegmentRomEnd;
        sRemix.biomeSnowPending = true;
        return &sTundraScene;
    }
#else
    (void)play;
    (void)sceneId;
#endif
    sRemix.biomeSnowPending = false;
    return scene;
}

// Snowfall: the game's own (otherwise unused) snow effect, drawn by Object_Kankyo with params 3.
static void RemixBiome_StartSnow(PlayState* play) {
    if (!sRemix.biomeSnowPending || (GET_PLAYER(play) == NULL)) {
        return;
    }
    sRemix.biomeSnowPending = false;
    // Flakes melt when they fall below the actor's height, so put it far below the world.
    Actor_Spawn(&play->actorCtx, play, ACTOR_OBJECT_KANKYO, 0.0f, -10000.0f, 0.0f, 0, 0, 0, 3);
    play->envCtx.precipitation[PRECIP_SNOW_MAX] = 64;
}

static void RemixBiome_Toggle(PlayState* play) {
#if REMIX_HAS_TUNDRA
    sRemix.biome = (sRemix.biome == REMIX_BIOME_TUNDRA) ? REMIX_BIOME_NORMAL : REMIX_BIOME_TUNDRA;
    SFX_PLAY_CENTERED(NA_SE_SY_DECIDE);

    if ((sRemix.biome == REMIX_BIOME_NORMAL) && (play->sceneId != SCENE_HYRULE_FIELD)) {
        RemixMenu_SetMessage("Hyrule Field is back to normal");
        return;
    }

    // Reload Hyrule Field in the chosen style: from where Link entered it, or from the castle bridge.
    RemixMenu_Close();
    play->nextEntranceIndex =
        (play->sceneId == SCENE_HYRULE_FIELD) ? gSaveContext.save.entranceIndex : ENTR_HYRULE_FIELD_0;
    play->transitionTrigger = TRANS_TRIGGER_START;
    play->transitionType = TRANS_TYPE_FADE_WHITE;
    RemixMenu_SetMessage((sRemix.biome == REMIX_BIOME_TUNDRA) ? "Welcome to the Frozen Tundra"
                                                              : "Back to Hyrule Field");
#else
    (void)play;
    RemixMenu_SetMessage("Biomes need a ROM build (see REMIX.md)");
    SFX_PLAY_CENTERED(NA_SE_SY_ERROR);
#endif
}

static s32 RemixMenu_ReadDirection(Input* input) {
    u16 btn = input->cur.button;
    s32 dir = 0;

    if (CHECK_BTN_ANY(btn, BTN_DUP | BTN_CUP) || (input->cur.stick_y > 40)) {
        dir |= REMIX_DIR_UP;
    }
    if (CHECK_BTN_ANY(btn, BTN_DDOWN | BTN_CDOWN) || (input->cur.stick_y < -40)) {
        dir |= REMIX_DIR_DOWN;
    }
    if (CHECK_BTN_ANY(btn, BTN_DLEFT | BTN_CLEFT) || (input->cur.stick_x < -40)) {
        dir |= REMIX_DIR_LEFT;
    }
    if (CHECK_BTN_ANY(btn, BTN_DRIGHT | BTN_CRIGHT) || (input->cur.stick_x > 40)) {
        dir |= REMIX_DIR_RIGHT;
    }
    return dir;
}

/** Directions that fire this frame: on press, then repeating while held. */
static s32 RemixMenu_RepeatDirection(Input* input) {
    s32 dir = RemixMenu_ReadDirection(input);

    if (dir != sRemix.heldDir) {
        sRemix.heldDir = dir;
        sRemix.holdTimer = 0;
        return dir;
    }
    if (dir == 0) {
        return 0;
    }
    sRemix.holdTimer++;
    if ((sRemix.holdTimer > 12) && ((sRemix.holdTimer % 3) == 0)) {
        return dir;
    }
    return 0;
}

static void RemixMenu_UpdateMain(PlayState* play, Input* input, s32 dir) {
    if (dir & REMIX_DIR_UP) {
        sRemix.cursor = (sRemix.cursor + REMIX_MAIN_MAX - 1) % REMIX_MAIN_MAX;
        SFX_PLAY_CENTERED(NA_SE_SY_CURSOR);
    }
    if (dir & REMIX_DIR_DOWN) {
        sRemix.cursor = (sRemix.cursor + 1) % REMIX_MAIN_MAX;
        SFX_PLAY_CENTERED(NA_SE_SY_CURSOR);
    }

    if (CHECK_BTN_ALL(input->press.button, BTN_B)) {
        RemixMenu_Close();
        return;
    }
    if (!CHECK_BTN_ALL(input->press.button, BTN_A)) {
        return;
    }

    switch (sRemix.cursor) {
        case REMIX_MAIN_ANCIENT:
            RemixMenu_Close();
            RemixLevel_GoToAncient(play);
            break;

        case REMIX_MAIN_SHRINE:
            RemixMenu_Close();
            RemixLevel_GoToShrine(play);
            break;

        case REMIX_MAIN_SEEKER:
            RemixMenu_Close();
            RemixLevel_GoToSeeker(play);
            break;

        case REMIX_MAIN_MAGNET:
            RemixMenu_Close();
            RemixLevel_GoToMagnet(play);
            break;

        case REMIX_MAIN_FORGE:
            RemixMenu_Close();
            RemixLevel_GoToForge(play);
            break;

        case REMIX_MAIN_TIME:
            RemixMenu_Close();
            RemixLevel_GoToTime(play);
            break;

        case REMIX_MAIN_YEARS:
            RemixMenu_Close();
            RemixLevel_GoToYears(play);
            break;

        case REMIX_MAIN_WARP:
            RemixMenu_Close();
            gSaveContext.gameMode = GAMEMODE_NORMAL;
            SET_NEXT_GAMESTATE(&play->state, MapSelect_Init, MapSelectState);
            play->state.running = false;
            break;

        case REMIX_MAIN_EQUIP:
            if (!sRemix.equipOn) {
                RemixMenu_EquipAll(play);
                RemixMenu_SetMessage("Fully equipped!");
            } else {
                RemixMenu_UnequipAll(play);
                RemixMenu_SetMessage("Your own items are back");
            }
            sRemix.equipOn = !sRemix.equipOn;
            SFX_PLAY_CENTERED(NA_SE_SY_DECIDE);
            break;

        case REMIX_MAIN_SPAWN:
            sRemix.page = REMIX_PAGE_SPAWN;
            sRemix.cursor = REMIX_SPAWN_ACTOR;
            SFX_PLAY_CENTERED(NA_SE_SY_DECIDE);
            break;

        case REMIX_MAIN_COSTUME:
            if (sRemix.playAs != REMIX_PLAY_AS_NONE) {
                RemixPossess_Stop(play);
                RemixMenu_SetMessage("Back to Link");
            } else {
                sRemix.playAs = REMIX_PLAY_AS_CUSTOM;
                RemixMenu_RequestObject(play, OBJECT_REMIX_MODEL);
                RemixMenu_SetMessage("Playing as your custom character");
            }
            SFX_PLAY_CENTERED(NA_SE_SY_DECIDE);
            break;

        case REMIX_MAIN_BIOME:
            RemixBiome_Toggle(play);
            break;

        case REMIX_MAIN_CLOSE:
            RemixMenu_Close();
            break;
    }
}

static void RemixMenu_UpdateSpawn(PlayState* play, Input* input, s32 dir) {
    s32 step = 0;
    s32 count;

    if (dir & REMIX_DIR_UP) {
        sRemix.cursor = (sRemix.cursor + REMIX_SPAWN_MAX - 1) % REMIX_SPAWN_MAX;
        SFX_PLAY_CENTERED(NA_SE_SY_CURSOR);
    }
    if (dir & REMIX_DIR_DOWN) {
        sRemix.cursor = (sRemix.cursor + 1) % REMIX_SPAWN_MAX;
        SFX_PLAY_CENTERED(NA_SE_SY_CURSOR);
    }
    if (dir & REMIX_DIR_LEFT) {
        step = -1;
    }
    if (dir & REMIX_DIR_RIGHT) {
        step = 1;
    }

    if (step != 0) {
        switch (sRemix.cursor) {
            case REMIX_SPAWN_LIST:
                sRemix.listAll = !sRemix.listAll;
                sRemix.actorIndex = 0;
                break;

            case REMIX_SPAWN_ACTOR:
                // Hold R to jump 10 at a time.
                count = RemixMenu_NumListed();
                if (CHECK_BTN_ALL(input->cur.button, BTN_R)) {
                    step *= 10;
                }
                sRemix.actorIndex = ((sRemix.actorIndex + step) % count + count) % count;
                break;

            case REMIX_SPAWN_PARAMS:
                // Hold R for 0x10 steps, Z for 0x100 steps.
                if (CHECK_BTN_ALL(input->cur.button, BTN_Z)) {
                    step *= 0x100;
                } else if (CHECK_BTN_ALL(input->cur.button, BTN_R)) {
                    step *= 0x10;
                }
                sRemix.params = (sRemix.params + step) & 0xFFFF;
                break;

            default:
                break;
        }
        SFX_PLAY_CENTERED(NA_SE_SY_CURSOR);
    }

    if (CHECK_BTN_ALL(input->press.button, BTN_B)) {
        sRemix.page = REMIX_PAGE_MAIN;
        sRemix.cursor = REMIX_MAIN_SPAWN;
        SFX_PLAY_CENTERED(NA_SE_SY_CANCEL);
        return;
    }
    if (!CHECK_BTN_ALL(input->press.button, BTN_A)) {
        return;
    }

    switch (sRemix.cursor) {
        case REMIX_SPAWN_LIST:
            sRemix.listAll = !sRemix.listAll;
            sRemix.actorIndex = 0;
            SFX_PLAY_CENTERED(NA_SE_SY_CURSOR);
            break;

        case REMIX_SPAWN_BACK:
            sRemix.page = REMIX_PAGE_MAIN;
            sRemix.cursor = REMIX_MAIN_SPAWN;
            SFX_PLAY_CENTERED(NA_SE_SY_CANCEL);
            break;

        case REMIX_SPAWN_PLAY_AS:
            if (RemixMenu_SelectedActor()->actorId == ACTOR_EN_REMIX_MODEL) {
                // The custom model has a proper costume mode, animated by Link's own movement.
                RemixPossess_Stop(play);
                sRemix.playAs = REMIX_PLAY_AS_CUSTOM;
                RemixMenu_RequestObject(play, OBJECT_REMIX_MODEL);
                RemixMenu_SetMessage("Playing as your custom character");
                RemixMenu_Close();
            } else {
                RemixPossess_Start(play, sRemix.actorIndex);
            }
            break;

        default:
            RemixMenu_Spawn(play);
            break;
    }
}

void RemixMenu_Update(PlayState* play) {
    Input* input = &play->state.input[0];
    s32 dir;

    if (sRemix.messageTimer > 0) {
        sRemix.messageTimer--;
    }

    RemixBiome_StartSnow(play);

    if (!sRemix.isOpen) {
        if (CHECK_BTN_ALL(input->press.button, BTN_DUP) && RemixMenu_CanOpen(play)) {
            RemixMenu_Open();
            // Treat the opening press as already held so it doesn't also move the cursor,
            // and fall through so it is swallowed below.
            sRemix.heldDir = RemixMenu_ReadDirection(input);
            sRemix.holdTimer = 0;
        } else {
            return;
        }
    } else if (!RemixMenu_CanOpen(play)) {
        // Something else took over (cutscene, transition): get out of the way.
        sRemix.isOpen = false;
        IREG(72) = sRemix.savedFreezeReg;
        return;
    } else if (CHECK_BTN_ALL(input->press.button, BTN_START)) {
        RemixMenu_Close();
    } else {
        dir = RemixMenu_RepeatDirection(input);
        if (sRemix.page == REMIX_PAGE_MAIN) {
            RemixMenu_UpdateMain(play, input, dir);
        } else {
            RemixMenu_UpdateSpawn(play, input, dir);
        }
    }

    // The menu owns controller 1 this frame: hide the input from Link, the pause menu and the HUD.
    input->cur.button = input->press.button = input->rel.button = 0;
    input->cur.stick_x = input->cur.stick_y = 0;
    input->press.stick_x = input->press.stick_y = 0;
    input->rel.stick_x = input->rel.stick_y = 0;
}

